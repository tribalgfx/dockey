const STRINGS = { nl, en };

const browserLanguage = () => (/^nl\b/i.test(navigator.language ?? '') ? 'nl' : 'en');
let systemLanguage = browserLanguage();
let lang = systemLanguage;

/** De weergavetaal van Windows, zoals de backend die meldt ("nl" of "en"). */
export function setSystemLanguage(code) {
  if (code === 'nl' || code === 'en') systemLanguage = code;
}

/** Kiest de taal bij een (nieuwe) configuratie; geeft true als die veranderde. */
export function setLanguage(config) {
  const next = config?.language === 'nl' || config?.language === 'en' ? config.language : systemLanguage;
  const changed = next !== lang;
  lang = next;
  document.documentElement.lang = lang;
  return changed;
}

export const language = () => lang;

/** Locale voor datums, tijden en getallen. */
export const locale = () => {
  if (lang === 'nl') return 'nl-NL';
  return /^en\b/i.test(navigator.language ?? '') ? navigator.language : 'en-GB';
};

/** De tekst bij `key`, met de waarden in `args`; valt terug op het Nederlands. */
export function t(key, ...args) {
  const v = STRINGS[lang][key] ?? nl[key];
  if (v == null) return key;
  return typeof v === 'function' ? v(...args) : v;
}

/** Een fout van de backend in de gekozen taal (zie net.rs); andere fouten ongewijzigd. */
export function errorText(err) {
  const text = String(err?.message ?? err);
  if (text === 'ERR_SCHEME') return t('err.scheme');
  if (text === 'ERR_NOT_IMAGE') return t('err.notImage');
  if (text === 'ERR_UPDATE_HASH') return t('err.updateHash');
  if (text === 'ERR_UPDATE_SIZE') return t('err.updateSize');
  if (text === 'ERR_UPDATE_NONE') return t('err.updateNone');
  const http = /^ERR_HTTP:(\d+)$/.exec(text);
  return http ? t('err.http', http[1]) : text;
}
